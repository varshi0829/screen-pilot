// Builds docs/METRICS.md from the measured result files. It reads
// only eval/results/*.json (written by the run-*.mjs scripts) — it computes
// no new numbers beyond formatting, and says so when a result is missing.
//
// Run: node eval/report.mjs

import fs from 'node:fs';
import path from 'node:path';
import { RESULTS_DIR } from './lib/harness.mjs';

const read = (name) => {
  const f = path.join(RESULTS_DIR, `${name}.json`);
  return fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, 'utf8')) : null;
};
const pct = (v) => (v == null ? 'n/a' : `${(100 * v).toFixed(1)}%`);
const ms = (s) => (s?.mean == null ? 'n/a' : `${Math.round(s.mean)} / ${Math.round(s.median)} / ${s.min} / ${s.max}`);
const num = (v, d = 1) => (v == null ? 'n/a' : Number(v).toFixed(d));

const visual = read('visual-accuracy');
const privacy = read('privacy');
const e2e = read('e2e-latency');
const res = read('resources');
const out = [];
const machine = (visual ?? privacy ?? e2e ?? res)?.machine;

out.push('# ScreenPilot — evaluation metrics (measured)');
out.push('');
out.push('Generated by `npm run eval:report` from the raw result files in `eval/results/`. Methodology, exact metric definitions and measurement limitations: `eval/README.md`.');
out.push('Every number below was **measured** by the harness in `eval/` against the unmodified extension;');
out.push('the only manually entered data are the ground-truth labels in `eval/ground-truth/`.');
if (machine) out.push(`\nMachine: ${machine.cpu}, ${machine.logicalCores} logical cores, ${machine.totalRamGB} GB RAM, ${machine.platform}.`);
out.push('');

// ── 1 ──
out.push('## 1. Visual-context accuracy');
if (!visual) out.push('\n_Not measured yet — run `node eval/run-visual.mjs`._');
else {
  const s = visual.summary;
  out.push(`\n**${s.overall.correct}/${s.overall.total} = ${pct(s.overall.accuracy)}** (local-only, i.e. without the cloud fallback: ${pct(s.localOnly.accuracy)})`);
  out.push(`\nDefinition: ${s.definition}. ${visual.config.cases.length} cases × ${visual.config.reps} repetitions; generated ${visual.generatedAt}.`);
  out.push('\n| Category | Correct / runs | Accuracy |\n|---|---|---|');
  for (const [k, v] of Object.entries(s.byCategory)) out.push(`| ${k} | ${v.correct}/${v.total} | ${pct(v.accuracy)} |`);
  out.push('\n| Decision mechanism | Correct / runs | Accuracy |\n|---|---|---|');
  for (const [k, v] of Object.entries(s.byMechanism)) out.push(`| ${k} | ${v.correct}/${v.total} | ${pct(v.accuracy)} |`);
  out.push(`\nTime to first highlight (mean / median / min / max ms): ${ms(s.timeToFirstHighlightMs)}`);
  out.push(`Moondream inference (ms): ${ms(s.moondreamLatencyMs)} · Qwen inference (ms): ${ms(s.qwenLatencyMs)}`);
  out.push('\n| Case | Goal | Expected | Actual (per rep) | Mechanism (per rep) |\n|---|---|---|---|---|');
  const byCase = {};
  for (const r of visual.runs) (byCase[r.caseId] ??= []).push(r);
  for (const [id, rs] of Object.entries(byCase)) {
    out.push(`| ${id} | ${rs[0].goal} | ${rs[0].expectedTargetId ?? '(nothing)'} | ${rs.map((r) => `${r.correct ? '✓' : '✗'} ${r.actualTargetId ?? '(none)'}`).join(', ')} | ${rs.map((r) => r.mechanism ?? '-').join(', ')} |`);
  }
}

// ── 2 ──
out.push('\n## 2. PII precision / recall');
if (!privacy) out.push('\n_Not measured yet — run `node eval/run-privacy.mjs`._');
else {
  out.push(`\nGround truth: ${privacy.groundTruth.sensitive} sensitive + ${privacy.groundTruth.nonSensitive} non-sensitive elements (\`${privacy.groundTruth.file}\`). ${privacy.definitions.pii}.`);
  out.push('\n| Detector | TP | FP | TN | FN | Precision | Recall | F1 |\n|---|---|---|---|---|---|---|---|');
  for (const [name, p] of Object.entries(privacy.pii)) {
    const c = p.counts;
    out.push(`| ${name} | ${c.tp} | ${c.fp} | ${c.tn} | ${c.fn} | ${pct(c.precision)} | ${pct(c.recall)} | ${pct(c.f1)} |`);
  }
  const v2 = privacy.pii.v2_agent_path;
  out.push(`\nMissed (FN): ${v2.falseNegatives.join(', ') || 'none'} · Wrongly flagged (FP): ${v2.falsePositives.join(', ') || 'none'}`);
  out.push('\n| Category | TP | FP | TN | FN |\n|---|---|---|---|---|');
  for (const [k, c] of Object.entries(v2.byCategory)) out.push(`| ${k} | ${c.tp} | ${c.fp} | ${c.tn} | ${c.fn} |`);
}

// ── 3 ──
out.push('\n## 3. Redaction precision');
if (!privacy) out.push('\n_Not measured yet — run `node eval/run-privacy.mjs`._');
else {
  out.push(`\nMeasured on the real JPEG returned by the extension's own \`CAPTURE_SCREENSHOT\` pipeline (evidence: \`eval/results/privacy-redacted-output-v2.jpg\`).`);
  out.push(`\n- Redaction precision (pixel): ${privacy.definitions.redactionPrecisionPixel}`);
  out.push(`- Sensitive coverage (pixel): ${privacy.definitions.sensitiveCoveragePixel}`);
  out.push(`- IoU: ${privacy.definitions.iou}`);
  out.push('\n| Detector | Pixel precision | Coverage of all GT sensitive px | Mean IoU (detected regions) | Detected regions IoU ≥ 0.5 | ≥ 0.9 | All GT regions IoU ≥ 0.5 | False-redaction area |\n|---|---|---|---|---|---|---|---|');
  for (const [name, r] of Object.entries(privacy.redaction)) {
    out.push(`| ${name} | ${pct(r.redactionPrecisionPixel)} | ${pct(r.sensitiveCoveragePixel)} | ${num(r.iouDetectedRegions.mean, 3)} | ${pct(r.shareDetectedRegionsIouAtLeast50)} | ${pct(r.shareDetectedRegionsIouAtLeast90)} | ${pct(r.shareAllSensitiveRegionsIouAtLeast50)} | ${r.falseRedactionPixels} px (${num(r.falseRedactionPctOfNonSensitiveArea, 2)}% of non-sensitive area) |`);
  }
  const img = privacy.redaction.v2_agent_path.image;
  out.push(`\nOutput image ${img.width}×${img.height}; viewport ${privacy.viewport.width}×${privacy.viewport.height} CSS px at devicePixelRatio ${privacy.viewport.dpr}; production CSS→image mapping consistent with the measured one: ${img.productionMappingConsistent}.`);
}

// ── 4 ──
out.push('\n## 4. Client resource utilization');
if (!res) out.push('\n_Not measured yet — run `node eval/run-e2e.mjs`._');
else {
  const r = res.resources;
  out.push(`\nInference device: ${r.inferenceDevice}. Sampling interval (ms): ${ms(r.samplingIntervalMs)}. CPU % is of the whole machine (${machine?.logicalCores} logical cores), as Task Manager reports it.`);
  out.push('\n| Window | Intervals | System CPU avg / peak | System RAM used avg / peak (MB) |\n|---|---|---|---|');
  for (const [w, a] of Object.entries(r.windows)) {
    out.push(`| ${w} | ${a.intervals} | ${num(a.systemCpuPct.avg)}% / ${num(a.systemCpuPct.peak)}% | ${num(a.systemRamUsedMB.avg, 0)} / ${num(a.systemRamUsedMB.peak, 0)} |`);
  }
  out.push('\n| Window | Process group | CPU avg / peak | RAM (working set) avg / peak (MB) |\n|---|---|---|---|');
  for (const w of ['idleBaseline', 'qwenInference', 'moondreamInference', 'allTaskActivity']) {
    const a = r.windows[w];
    if (!a) continue;
    for (const [g, v] of Object.entries(a.perGroup)) {
      out.push(`| ${w} | ${g} | ${num(v.cpuPct.avg)}% / ${num(v.cpuPct.peak)}% | ${num(v.ramMB.avg, 0)} / ${num(v.ramMB.peak, 0)} |`);
    }
  }
  out.push('\nModel footprint reported by Ollama (`/api/ps`):');
  for (const m of r.ollamaReportedModels) out.push(`- ${m.name}: ${m.sizeMB} MB (VRAM ${m.sizeVramMB} MB)`);
}

// ── 5 ──
out.push('\n## 5. End-to-end latency');
if (!e2e) out.push('\n_Not measured yet — run `node eval/run-e2e.mjs`._');
else {
  out.push(`\nGoal submitted → verified completion (ScreenPilot's own STATE timestamps). ${e2e.config.reps} measured runs per task after 1 warm-up. "System" = total − simulated user action. All figures ms: mean / median / min / max over completed runs.`);
  out.push('\n| Task (path) | Completed | Total | System | Planning | Verification | Simulated user | Qwen inference | Moondream inference | Warm-up total |\n|---|---|---|---|---|---|---|---|---|---|');
  for (const [id, l] of Object.entries(e2e.latency)) {
    out.push(`| ${id} (${l.path}) | ${l.completedRuns}/${l.measuredRuns} | ${ms(l.totalMs)} | ${ms(l.systemMs)} | ${ms(l.planningMs)} | ${ms(l.verificationMs)} | ${ms(l.simulatedUserActionMs)} | ${ms(l.qwenInferenceMs)} | ${ms(l.moondreamInferenceMs)} | ${l.warmupRun?.totalMs ?? 'n/a'} (${l.warmupRun?.outcome ?? '-'}) |`);
  }
}

const file = path.join(RESULTS_DIR, '..', '..', 'docs', 'METRICS.md');
fs.writeFileSync(file, out.join('\n') + '\n');
console.log(`Wrote ${file}`);
